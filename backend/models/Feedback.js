import mongoose from 'mongoose'

const feedbackSchema = new mongoose.Schema(
  {
    table: {
      type: String,
      required: true,
      trim: true,
    },
    rating: {
      type: Number,
      required: true,
      min: 1,
      max: 5,
    },
    comment: {
      type: String,
      default: '',
    },
    customerName: {
      type: String,
      required: true,
      trim: true,
    },
    createdAt: {
      type: Date,
      default: Date.now,
    },
  },
  { timestamps: true }
)

const Feedback = mongoose.model('Feedback', feedbackSchema)

export default Feedback
